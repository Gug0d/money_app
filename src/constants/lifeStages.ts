export function getLifeStage(level: number): LifeStage {
  const sortedStages = [...lifeStages].sort((a, b) => a.level - b.level);

  let currentStage = sortedStages[0];

  for (const stage of sortedStages) {
    if (level >= stage.level) {
      currentStage = stage;
    }
  }

  return currentStage;
}

export function getNextLifeStage(level: number): LifeStage | null {
  return lifeStages.find((stage) => stage.level > level) ?? null;
}